"""Clean end-to-end run on DuckDB that records the numbers quoted in the README.

Steps: generate data -> dbt build as of load 1 -> dbt build with load 2 (incremental)
-> source freshness. Writes docs/benchmark.md with row counts and timings.

    .venv/bin/python scripts/benchmark.py --customers 20000
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import time
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
DBT = str(ROOT / ".venv/bin/dbt")
PY = str(ROOT / ".venv/bin/python")


def run(cmd: list[str]) -> float:
    t0 = time.perf_counter()
    subprocess.run(cmd, cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    return time.perf_counter() - t0


def results() -> dict:
    r = json.loads((ROOT / "target/run_results.json").read_text())
    statuses: dict[str, int] = {}
    for x in r["results"]:
        statuses[x["status"]] = statuses.get(x["status"], 0) + 1
    return {"dbt_elapsed_s": r["elapsed_time"], "statuses": statuses, "nodes": len(r["results"])}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--customers", type=int, default=20000)
    ap.add_argument("--report", default="docs/benchmark.md")
    args = ap.parse_args()

    db = ROOT / "data/warehouse.duckdb"
    db.unlink(missing_ok=True)
    flags = ["--profiles-dir", ".", "--target", "dev"]

    t_gen = run([PY, "generator/generate.py", "--customers", str(args.customers)])
    run([DBT, "deps", *flags])
    t_load1 = run([DBT, "build", *flags, "--vars", '{as_of_load_date: "2025-10-01"}'])
    r_load1 = results()
    con = duckdb.connect(str(db), read_only=True)
    facts = ["core.fct_subscription_events", "core.fct_payments", "core.fct_feature_usage"]
    after_load1 = {t: con.execute(f"select count(*) from {t}").fetchone()[0] for t in facts}
    con.close()

    t_load2 = run([DBT, "build", *flags])
    r_load2 = results()
    t_fresh = run([DBT, "source", "freshness", *flags])

    con = duckdb.connect(str(db), read_only=True)
    tables = [
        "snapshots.snap_customers", "core.dim_customer", "core.dim_plan", "core.dim_date",
        *facts,
        "subscription.mart_acquisition_cohorts", "subscription.mart_cohort_retention",
        "subscription.mart_cohort_ltv", "subscription.mart_subscription_monthly",
        "product.mart_feature_usage_monthly", "product.mart_feature_engagement_churn",
    ]
    counts = {t: con.execute(f"select count(*) from {t}").fetchone()[0] for t in tables}
    scd2 = con.execute("select count(*) from core.dim_customer where version_number > 1").fetchone()[0]
    landing = {
        f: con.execute(
            f"select count(*) from read_parquet('data/landing/{f}/*/*.parquet')").fetchone()[0]
        for f in ["customers", "plans", "subscription_events", "payments", "feature_usage"]
    }
    con.close()

    lines = [
        "# Benchmark: local DuckDB run",
        "",
        f"Generated by `scripts/benchmark.py --customers {args.customers} --report {args.report}` on "
        f"{time.strftime('%Y-%m-%d')} ({platform.system()} {platform.machine()}, "
        f"Python {platform.python_version()}, DuckDB {duckdb.__version__}).",
        "Timings are wall-clock for the whole command, including dbt start-up and parsing.",
        "",
        "## Timings",
        "",
        "| Step | Seconds |",
        "|---|---|",
        f"| Generate synthetic landing data | {t_gen:.1f} |",
        f"| `dbt build`, load 1 (backfill, full refresh) | {t_load1:.1f} |",
        f"| `dbt build`, load 2 (incremental MERGE + SCD2) | {t_load2:.1f} |",
        f"| `dbt source freshness` | {t_fresh:.1f} |",
        "",
        f"dbt-reported elapsed: load 1 {r_load1['dbt_elapsed_s']:.2f}s, "
        f"load 2 {r_load2['dbt_elapsed_s']:.2f}s.",
        f"Node results load 1: {r_load1['statuses']}; load 2: {r_load2['statuses']} "
        f"({r_load2['nodes']} nodes: models, seeds, snapshot, data tests, unit tests, hooks).",
        "",
        "## Landing rows (parquet, both loads)",
        "",
        "| Feed | Rows |",
        "|---|---|",
        *[f"| {k} | {v:,} |" for k, v in landing.items()],
        "",
        "## Warehouse rows after load 2",
        "",
        "| Relation | Rows | Rows after load 1 |",
        "|---|---|---|",
        *[f"| {k} | {v:,} | {after_load1[k]:,} |" if k in after_load1 else f"| {k} | {v:,} | |"
          for k, v in counts.items()],
        "",
        f"SCD2: {scd2:,} customers gained a second profile version from the load 2 delta.",
        "",
    ]
    out = ROOT / args.report
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
